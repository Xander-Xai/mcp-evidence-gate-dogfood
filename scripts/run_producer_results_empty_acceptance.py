#!/usr/bin/env python3
"""Exercise Producer PR #4's Results=[] fail-closed behavior.

The workflow checks out the Producer at an immutable SHA and uses a deterministic
scanner stub only for the otherwise hard-to-reproduce empty-results edge case.
All receipts and evidence are still generated by the checked-out Producer code.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path
from types import SimpleNamespace


def _digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def run(*, producer_root: Path, binary: Path, artifact: Path, output: Path, producer_sha: str, core_sha: str) -> dict[str, object]:
    sys.path.insert(0, str(producer_root.resolve()))
    from src import producer  # type: ignore[import-not-found]

    artifact = artifact.resolve()
    binary = binary.resolve()
    output = output.resolve()
    producer.PINNED_TRIVY_SHA256[sys.platform] = _digest(binary)
    producer.trivy_version = lambda _binary: "0.74.0"

    def fake_scan(argv: list[str], **_kwargs: object) -> SimpleNamespace:
        output_path = Path(argv[argv.index("--output") + 1])
        output_path.parent.mkdir(parents=True, exist_ok=True)
        report = {
            "Trivy": {"Version": "0.74.0"},
            "ArtifactName": str(artifact),
            "Results": [],
        }
        output_path.write_text(json.dumps(report, sort_keys=True), encoding="utf-8")
        return SimpleNamespace(returncode=0, stdout="", stderr="")

    producer.subprocess.run = fake_scan
    producer_exit = producer.run(str(binary), artifact, output)
    receipt = json.loads((output / "receipt.json").read_text(encoding="utf-8"))
    evidence = json.loads((output / "evidence.json").read_text(encoding="utf-8"))
    raw = json.loads((output / "trivy.raw.json").read_text(encoding="utf-8"))
    execution = evidence["scanner_execution"]

    assert producer_exit == 1
    assert receipt["verdict"] == "inconclusive"
    assert execution["schema_version"] == "project-defined-scanner-execution-v1"
    assert execution["completeness_status"] == "incomplete"
    assert execution["required_work_completed"] is False
    assert execution["failed_components"] == ["result_sections"]
    assert execution["completeness_reason"] == "trivy_result_sections_missing"
    assert raw["Results"] == []

    manifest = {
        "schema_version": "dogfood-producer-results-empty-runtime-v1",
        "producer_pr_head": producer_sha,
        "core_sha": core_sha,
        "artifact": str(artifact),
        "producer_exit_code": producer_exit,
        "producer_receipt_digest": "sha256:" + _digest(output / "receipt.json"),
        "producer_evidence_digest": "sha256:" + _digest(output / "evidence.json"),
        "producer_raw_digest": "sha256:" + _digest(output / "trivy.raw.json"),
        "receipt_verdict": receipt["verdict"],
        "scanner_execution": execution,
    }
    (output / "producer-results-empty-manifest.json").write_text(
        json.dumps(manifest, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )
    return manifest


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--producer-root", required=True, type=Path)
    parser.add_argument("--binary", required=True, type=Path)
    parser.add_argument("--artifact", required=True, type=Path)
    parser.add_argument("--out", required=True, type=Path)
    parser.add_argument("--producer-sha", required=True)
    parser.add_argument("--core-sha", required=True)
    args = parser.parse_args(argv)
    print(json.dumps(run(
        producer_root=args.producer_root,
        binary=args.binary,
        artifact=args.artifact,
        output=args.out,
        producer_sha=args.producer_sha,
        core_sha=args.core_sha,
    ), indent=2, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
